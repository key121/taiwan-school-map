def split_pairs(pdf):
    import pymupdf
    pairs = collections.Counter(); last = None
    for pg in pymupdf.open(pdf):
        t = pg.get_text()
        m = re.findall(r'村里：(\S+)\s*\n\s*鄰：(\d+)鄰', t)
        if len(m) >= 2: last = (m[0][0], int(m[0][1]), m[1][0], int(m[1][1]))
        assert last and last[0] == '員山村', last
        pairs[last] += len(re.findall(r'號\s*\n', t))
    return pairs
