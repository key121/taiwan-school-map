def seg(a, b, s, t, m=None, p=None):
    x = {'a': a, 'b': b, 's': s, 't': t}
    if m: x['m'] = m
    if p: x['p'] = p
    return x
def whole(L, s, t): return [seg(1, L, s, t)]
def cond(a, b, p, t, m): return seg(a, b, [], t, [m], p)

